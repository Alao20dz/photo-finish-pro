const DICTS: Record<Lang, Partial<Dict>> = { ar, fr, en };

interface I18nCtx {
  lang: Lang;
  dir: "rtl" | "ltr";
  t: (k: keyof Dict) => string;
  setLang: (l: Lang) => void;
}

const Ctx = createContext<I18nCtx>({ lang: "ar", dir: "rtl", t: (k) => ar[k], setLang: () => {} });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    // تهيئة اللغة المحفوظة بعد التركيب (نمط تهيئة جلسة — لا قيمة أثناء SSR)
    const saved = (typeof window !== "undefined" && localStorage.getItem("pf_lang")) as Lang | null;
    if (saved && ["ar", "fr", "en"].includes(saved)) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLangState(saved);
    }
  }, []);

  const dir = LANGS.find((l) => l.code === lang)?.dir || "rtl";

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = dir;
    }
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("pf_lang", l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((k: keyof Dict) => DICTS[lang][k] ?? ar[k] ?? String(k), [lang]);

  return <Ctx.Provider value={{ lang, dir, t, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
