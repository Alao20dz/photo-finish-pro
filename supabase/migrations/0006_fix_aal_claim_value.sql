-- ═══════════════════════════════════════════════════════════════
-- 0006: تصحيح قيمة ادعاء AAL في بوابة MFA
-- ═══════════════════════════════════════════════════════════════
-- المشكلة: aal2_required() في 0004 قارنت الادعاء بـ 'al2' بينما
-- Supabase يُصدر الجلسات بالقيم الرسمية 'aal1' / 'aal2' (وثائق JWT
-- Claims الرسمية: aal: 'aal1' | 'aal2'). النتيجة: جلسة MFA حقيقية
-- كانت ستُحجب دائماً من سياسات البوابة التقييدية.
-- الاختبارات السحابية السابقة كانت تستخدم 'al2' لمطابقة الخلل نفسه —
-- صُححت هي الأخرى إلى 'aal2' في نفس هذا الإصدار.
-- المرجع: https://supabase.com/docs/guides/auth/jwt-fields
-- ═══════════════════════════════════════════════════════════════

create or replace function public.aal2_required() returns boolean
language sql stable as $$
  select coalesce(auth.jwt()->>'aal', 'aal1') = 'aal2';
$$;
